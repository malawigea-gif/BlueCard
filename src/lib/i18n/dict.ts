export const DICT: Record<Locale, Record<DictKey, string>> = { en, de };

export type TFn = (key: DictKey, vars?: Record<string, string | number>) => string;

export function makeT(locale: Locale): TFn {
  const d = DICT[locale];
  return (key, vars) => {
    let s = d[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** Picks the German field when viewing in German and it is filled in; otherwise the English one. */
export function localized<T extends Record<string, unknown>>(obj: T, field: keyof T & string, locale: Locale): string {
  let v = (obj[field] as string | null | undefined) ?? "";
  if (locale === "de") {
    const de = obj[`${field}De` as keyof T] as string | null | undefined;
    if (de && de.trim()) v = de;
  }
  // titles are always shown bold, so "**…**" marks typed into a title are dropped
  return field === "title" ? v.replace(/\*\*/g, "").trim() : v;
}

export function fmtDate(d: Date | string, locale: Locale) {
  const x = typeof d === "string" ? new Date(d) : d;
  return x.toLocaleDateString(DATE_LOCALE[locale], { year: "numeric", month: "long", day: "numeric" });
}

export function statusLabel(status: string, t: TFn) {
  return status === "PENDING" || status === "APPROVED" || status === "REJECTED" ? t(`status.${status}`) : status;
}

export function genderLabel(gender: string, t: TFn) {
  const g = gender.toUpperCase(); // older registrations stored "Male" / "Female" / "Other"
  return g === "MALE" || g === "FEMALE" || g === "OTHER" ? t(`gender.${g}`) : gender;
}
